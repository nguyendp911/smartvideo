// node generate.mjs [id ...]  -> writes Resources/MockupStudio/*.webp + the Swift catalog.
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, ASSETS } from './catalog.mjs';
import { samplePhoto } from './preview.mjs';
import { light } from './builders/light.mjs';
import { nature } from './builders/nature.mjs';
import { photography, glass } from './builders/effects.mjs';
import { weather, retro } from './builders/weather.mjs';
import { texture, background } from './builders/surface.mjs';
import { frames, products } from './builders/scenes.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const outDir = path.join(repo, 'SmartVideo/Resources/MockupStudio');
const swiftFile = path.join(repo, 'SmartVideo/Models/MockupStudioCatalogData.swift');
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(path.join(here, 'out'), { recursive: true });

const registry = { light, nature, photo: photography, glass, weather, retro, texture, background, frames, products };
const SHARP_BLEND = {
  normal: 'over', multiply: 'multiply', screen: 'screen', overlay: 'overlay', softLight: 'soft-light',
  hardLight: 'hard-light', darken: 'darken', lighten: 'lighten', colorDodge: 'colour-dodge',
  colorBurn: 'colour-burn', difference: 'difference',
};
const THUMB = 256;

const only = new Set(process.argv.slice(2));
const sample = await sharp(Buffer.from(samplePhoto())).png().toBuffer();

function build(asset) {
  const fn = registry[asset.group]?.[asset.id];
  if (!fn) throw new Error(`no builder for ${asset.id}`);
  const out = fn();
  return typeof out === 'string' ? { svg: out, slot: null } : out;
}

async function thumbnail(asset, svgBuf, slot) {
  let canvas;
  if (asset.kind === 'overlay') {
    const base = await sharp(sample).resize(THUMB, THUMB).png().toBuffer();
    const raw = await sharp(svgBuf).resize(THUMB, THUMB).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const px = raw.data;
    for (let i = 3; i < px.length; i += 4) px[i] = Math.round(px[i] * asset.opacity);
    const overlay = await sharp(px, { raw: { width: THUMB, height: THUMB, channels: 4 } }).png().toBuffer();
    canvas = await sharp(base).composite([{ input: overlay, blend: SHARP_BLEND[asset.blend] ?? 'over' }]).toBuffer();
  } else if (asset.kind === 'background') {
    const bg = await sharp(svgBuf).resize(THUMB, THUMB).png().toBuffer();
    const inset = Math.round(THUMB * 0.62);
    const card = await sharp(sample).resize(inset, inset).png().toBuffer();
    const shadow = await sharp({ create: { width: inset, height: inset, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0.45 } } }).blur(6).png().toBuffer();
    const off = Math.round((THUMB - inset) / 2);
    canvas = await sharp(bg).composite([{ input: shadow, left: off + 3, top: off + 8 }, { input: card, left: off, top: off }]).toBuffer();
  } else {
    // Scene: put the sample photo in the window exactly as the app does.
    const [w, h] = asset.size;
    const sx = Math.round(slot.x * w), sy = Math.round(slot.y * h), sw = Math.round(slot.w * w), sh = Math.round(slot.h * h);
    const photo = await sharp(sample).resize(sw, sh, { fit: 'cover' }).png().toBuffer();
    const art = await sharp(svgBuf).png().toBuffer();
    const full = await sharp({ create: { width: w, height: h, channels: 4, background: '#202020' } })
      .composite([{ input: photo, left: sx, top: sy }, { input: art, left: 0, top: 0 }]).png().toBuffer();
    canvas = await sharp(full).resize(THUMB, THUMB, { fit: 'cover' }).toBuffer();
  }
  return sharp(canvas).webp({ quality: 82 }).toBuffer();
}

const results = [];
for (const asset of ASSETS) {
  const { svg, slot: slotPx } = build(asset);
  const svgBuf = Buffer.from(svg);
  const meta = await sharp(svgBuf).metadata();
  const slot = slotPx ? { x: slotPx.x / meta.width, y: slotPx.y / meta.height, w: slotPx.w / meta.width, h: slotPx.h / meta.height } : null;
  if (only.size === 0 || only.has(asset.id)) {
    const opaque = asset.kind === 'background';
    const file = path.join(outDir, `ms_${asset.id}.webp`);
    await sharp(svgBuf).flatten(opaque ? { background: '#ffffff' } : false).webp({ quality: opaque ? 84 : 80, alphaQuality: 92, effort: 4 }).toFile(file);
    const thumb = await thumbnail(asset, svgBuf, slot);
    fs.writeFileSync(path.join(outDir, `ms_${asset.id}_thumb.webp`), thumb);
    const bytes = fs.statSync(file).size;
    console.log(`${asset.id.padEnd(24)} ${meta.width}x${meta.height} ${(bytes / 1024).toFixed(0)} KB`);
  }
  results.push({ asset, width: meta.width, height: meta.height, slot });
}

// ---- Swift catalog -----------------------------------------------------
const s = (v) => JSON.stringify(v);
const n = (v) => (Math.round(v * 10000) / 10000).toString();
let swift = `// GENERATED by scripts/mockup-assets/generate.mjs from catalog.mjs - do not edit by hand.\n`;
swift += `import Foundation\n\nextension MockupStudioCatalog {\n    static let allAssets: [MockupStudioAsset] = [\n`;
for (const { asset, width, height, slot } of results) {
  swift += `        MockupStudioAsset(\n` +
    `            id: ${s(asset.id)}, name: ${s(asset.name)}, category: .${asset.category}, kind: .${asset.kind},\n` +
    `            fileType: .webp, tags: ${s(asset.tags)},\n` +
    `            description: ${s(asset.description)},\n` +
    `            defaultOpacity: ${n(asset.opacity)}, defaultBlendMode: .${asset.blend}, isPremium: ${asset.premium},\n` +
    `            slot: ${slot ? `MockupStudioSlot(x: ${n(slot.x)}, y: ${n(slot.y)}, width: ${n(slot.w)}, height: ${n(slot.h)})` : 'nil'},\n` +
    `            pixelWidth: ${width}, pixelHeight: ${height}),\n`;
}
swift += `    ]\n\n    static let categoryTitles: [MockupStudioCategory: (english: String, vietnamese: String)] = [\n`;
for (const c of CATEGORIES) swift += `        .${c.id}: (${s(c.title)}, ${s(c.vi)}),\n`;
swift += `    ]\n}\n`;
fs.writeFileSync(swiftFile, swift.replace(/\n/g, '\r\n'));
console.log(`\n${results.length} assets, Swift catalog written.`);

// ---- contact sheet of every thumbnail ----------------------------------
const cols = 9, cell = 160;
const rows = Math.ceil(results.length / cols);
const tiles = [];
for (let i = 0; i < results.length; i++) {
  const f = path.join(outDir, `ms_${results[i].asset.id}_thumb.webp`);
  tiles.push({ input: await sharp(f).resize(cell, cell).png().toBuffer(), left: (i % cols) * cell, top: Math.floor(i / cols) * cell });
}
await sharp({ create: { width: cols * cell, height: rows * cell, channels: 3, background: '#222' } }).composite(tiles).jpeg({ quality: 85 }).toFile(path.join(here, 'out/all-thumbs.jpg'));
